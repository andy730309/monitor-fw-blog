#!/usr/bin/env python3
"""Generate _data/blueprint.yml from ~/.hermes/blog/BLUEPRINT.md (series index page data).
An article counts as published when a post links to it: either front matter
`blueprint_id: "2-2"` in a source post, or the fallback map below. Output is plain YAML (no deps)."""
import os, re, sys, glob, json
src = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/.hermes/blog")
site = sys.argv[2] if len(sys.argv) > 2 else os.path.expanduser("~/.hermes/blog-site")
FALLBACK = {  # blueprint id -> post slug (filename without date), for posts lacking blueprint_id
    "0-1": "monitor-system-block-diagram", "0-2": "monitor-fw-engineer-role-odm",
    "0-3": "video-interface-overview", "2-1": "edid-intro-edid-decode",
    "2-6": "ddc-ci-mccs-ddcutil-intro", "4-3": "dpcd-sink-capability",
    "4-5": "dsc-sink-params-slice-bpp-buffer-model", "6-1": "color-basics-rgb-gamma-cct-gamut",
}
slugs = {}
for p in glob.glob(os.path.join(src, "posts", "*.md")):
    slug = re.sub(r"^\d{4}-\d{2}-\d{2}-", "", os.path.basename(p))[:-3]
    head = open(p, encoding="utf-8").read(3000)
    m = re.search(r"^blueprint_id\s*:\s*['\"]?([\d]+-[\d]+)", head, re.M)
    if m: slugs[m.group(1)] = slug
existing = {re.sub(r"^\d{4}-\d{2}-\d{2}-", "", os.path.basename(p))[:-3] for p in glob.glob(os.path.join(src, "posts", "*.md"))}
for k, v in FALLBACK.items():
    if v in existing: slugs.setdefault(k, v)
q = lambda s: json.dumps(s, ensure_ascii=False)  # JSON strings are valid YAML
out, part = [], None
for line in open(os.path.join(src, "BLUEPRINT.md"), encoding="utf-8"):
    m = re.match(r"^###\s+(Part\s+\d+)\s*[\u3000 ]\s*(.+?)\s*$", line)
    if m:
        out.append(f"- part: {q(m.group(1))}\n  title: {q(m.group(2))}\n  items:"); part = True; continue
    if line.startswith("## ") and part: part = None
    m = re.match(r"^\|\s*(\d+-\d+)[^|]*\|\s*([^|]+?)\s*\|\s*([^|]*?)\s*\|\s*([^|]*?)\s*\|", line)
    if m and part:
        i = m.group(1)
        out.append(f"    - id: {q(i)}\n      title: {q(m.group(2))}\n      goal: {q(m.group(4))}\n      post: {q(slugs.get(i, ''))}")
os.makedirs(os.path.join(site, "_data"), exist_ok=True)
dst = os.path.join(site, "_data", "blueprint.yml")
text = "# generated by scripts/gen_blueprint_data.py from BLUEPRINT.md - do not edit\n" + "\n".join(out) + "\n"
if not os.path.exists(dst) or open(dst, encoding="utf-8").read() != text:
    open(dst, "w", encoding="utf-8").write(text)
print(f"blueprint: {sum(1 for l in out if '- id:' in l)} items, {len(slugs)} published")
